import 'mood_scale.dart';

enum DayPart { daytime, evening }

/// Evening tips from this hour until [kDayStartHour].
const int kEveningStartHour = 17;
const int kDayStartHour = 5;

/// 3×3 mood matrix, with daytime / evening tip packs.
class MoodAdviceService {
  MoodAdviceService._();

  /// Daytime vs evening pack from the clock of [markedAt] (or [now]).
  static DayPart dayPartFor({DateTime? markedAt, DateTime? now}) {
    final int h = (markedAt ?? now ?? DateTime.now()).hour;
    return (h >= kEveningStartHour || h < kDayStartHour)
        ? DayPart.evening
        : DayPart.daytime;
  }

  /// Tip for this mood at [markedAt] (defaults to now). Persist the result
  /// on the entry so it stays fixed after the user saves.
  static String forMood({
    required int energyPercent,
    required int pleasantnessPercent,
    DateTime? date,
    DateTime? markedAt,
    DateTime? now,
  }) {
    final DateTime entryDate = date ?? DateTime.now();
    final DateTime markTime = markedAt ?? now ?? DateTime.now();
    final DayPart part = dayPartFor(markedAt: markTime);

    final int e = MoodScale.toPercent(energyPercent);
    final int p = MoodScale.toPercent(pleasantnessPercent);
    final int row = (e / 34).floor().clamp(0, 2); // low → high energy
    final int col = (p / 34).floor().clamp(0, 2); // low → high pleasantness
    final int section = row * 3 + col;

    final List<List<String>> pack = part == DayPart.daytime
        ? _daytimeTips
        : _eveningTips;
    final List<String> tips = pack[section];
    final int daySeed =
        entryDate.year * 10000 + entryDate.month * 100 + entryDate.day;
    final int tipIndex =
        (daySeed + section * 17 + part.index * 41 + markTime.hour) %
        tips.length;

    return tips[tipIndex];
  }

